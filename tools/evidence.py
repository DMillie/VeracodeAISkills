#!/usr/bin/env python3
"""Cross-check the skills against the evidence register.

  python3 tools/evidence.py check          every ID cited in a skill has a register entry, every entry is
                                           cited, suffixes agree with the basis, no old-style tag is left
  python3 tools/evidence.py index          rewrite evidence/INDEX.md (ID -> basis, date, where cited)
  python3 tools/evidence.py stale [days]   list entries checked more than <days> ago (default 180)

Skill text carries only short IDs: [PS-04] observed, [INT-12~] read not run, [UPL-02?] carried over.
The register (evidence/register/<PREFIX>.md) holds date, source and the claim as first recorded.
Stdlib only. Exit 1 on any error in `check`.
"""
import datetime, glob, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); os.chdir(ROOT)
SKILL_DIRS = ['shared'] + sorted(d for d in os.listdir('.') if os.path.isfile(d + '/SKILL.md'))
ID = re.compile(r'\[([A-Z]{2,5}-\d{2,3})([~?]?)\]')
OLD = re.compile(r'\[v: ?\d|\[live \d|\*\*\[20\d\d-\d\d')
SUFFIX = {'lab': '', 'docs': '~', 'source': '~', 'dated': '~', 'carried': '?'}

def register():
    reg = {}
    for f in sorted(glob.glob('evidence/register/*.md')):
        for line in open(f, encoding='utf-8'):
            c = [x.strip() for x in line.strip().strip('|').split('|')]
            if len(c) >= 6 and re.fullmatch(r'[A-Z]{2,5}-\d{2,3}', c[0]):
                if c[0] in reg: print('ERROR duplicate register entry', c[0])
                reg[c[0]] = dict(basis=c[1], checked=c[2], source=c[3], claim=c[4], file=c[5].strip('`'), reg=f)
    return reg

def citations():
    cites, old = {}, []
    for d in SKILL_DIRS:
        for f in sorted(glob.glob(d + '/**/*', recursive=True)):
            if not os.path.isfile(f) or not f.endswith(('.md', '.yml', '.yaml', '.txt')): continue
            for n, line in enumerate(open(f, encoding='utf-8', errors='replace'), 1):
                for m in ID.finditer(line): cites.setdefault(m.group(1), []).append((f, n, m.group(2)))
                if OLD.search(line): old.append((f, n, line.strip()[:90]))
    return cites, old

def check():
    reg, (cites, old) = register(), citations(); err = 0
    for i, where in sorted(cites.items()):
        if i not in reg: err += 1; print('ERROR %s cited in %s:%d has no register entry' % (i, where[0][0], where[0][1])); continue
        want = SUFFIX.get(reg[i]['basis'])
        if want is None: err += 1; print('ERROR %s: unknown basis %r' % (i, reg[i]['basis']))
        for f, n, suf in where:
            if want is not None and suf != want: err += 1; print('ERROR %s in %s:%d is written [%s%s], register basis %s needs [%s%s]' % (i, f, n, i, suf, reg[i]['basis'], i, want))
    for i in sorted(set(reg) - set(cites)): err += 1; print('ERROR %s is in %s and cited nowhere (remove the entry or restore the citation)' % (i, reg[i]['reg']))
    for f, n, t in old: err += 1; print('ERROR old-style provenance tag in %s:%d: %s' % (f, n, t))
    print('%d register entries, %d cited IDs, %d errors' % (len(reg), len(cites), err)); return 1 if err else 0

def index():
    reg, (cites, _) = register(), citations()
    with open('evidence/INDEX.md', 'w', encoding='utf-8') as o:
        o.write('# Evidence index (generated by `tools/evidence.py index`; do not edit)\n\n| ID | Basis | Checked | Cited in |\n|---|---|---|---|\n')
        for i in sorted(reg, key=lambda x: (x.split('-')[0], int(x.split('-')[1]))):
            src = sorted({f for f, _, _ in cites.get(i, []) if f.startswith('shared/') or not os.path.exists('shared/' + f.split('/', 1)[1])})
            o.write('| %s | %s | %s | %s |\n' % (i, reg[i]['basis'], reg[i]['checked'], ', '.join('`%s`' % s for s in src) or '-'))
    print('wrote evidence/INDEX.md (%d entries)' % len(reg)); return 0

def stale(days):
    today = datetime.date.today(); n = 0
    for i, e in sorted(register().items()):
        d = e['checked'] + ('-01' if len(e['checked']) == 7 else '')
        try: age = (today - datetime.date.fromisoformat(d)).days
        except ValueError: print('%s: unreadable date %r' % (i, e['checked'])); continue
        if age > days or e['basis'] == 'carried': n += 1; print('%-8s %-8s %s  %4d days  %s' % (i, e['basis'], e['checked'], age, e['claim'][:90]))
    print('%d entries to re-check' % n); return 0

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else ''
    sys.exit(check() if cmd == 'check' else index() if cmd == 'index' else stale(int(sys.argv[2]) if len(sys.argv) > 2 else 180) if cmd == 'stale' else (print(__doc__) or 2))
